// Builds the browser control layer into the extension. The extension has no build step of its own, so the results are
// committed and scripts/check.mjs holds them to the pins this script writes.
//
//   node build.mjs           writes the files below
//   node build.mjs --check   builds in memory and fails when a committed file differs from the build
//
//   extension/lib/browser-control/layer.js          the layer, puppeteer-core and zod as one minified ES module
//   extension/lib/browser-control/catalogue.js      the layer's tool catalogue as data (names, descriptions, schemas)
//   extension/assets/licenses/browser-control.txt   the notices for the code inside layer.js
//   scripts/generated.json                          the pins: byte length, SHA-256 and the hash of the sources built
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
import { layerSourceHash } from '../scripts/generated.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const extension = resolve(root, 'extension');
const check = process.argv.includes('--check');
const packageJson = JSON.parse(await readFile(join(here, 'package.json'), 'utf8'));

const LAYER = 'lib/browser-control/layer.js';
const CATALOGUE = 'lib/browser-control/catalogue.js';
const NOTICES = 'assets/licenses/browser-control.txt';
const PINS = resolve(root, 'scripts', 'generated.json');

const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
// The manifest of an installed package. A missing one means npm ci was not run.
const installed = name => {
  const file = join(here, 'node_modules', name, 'package.json');
  if (!existsSync(file)) throw new Error(`Missing ${name}. Run "npm ci" in browser-control first.`);
  return JSON.parse(readFileSync(file, 'utf8'));
};

const versions = { puppeteer: installed('puppeteer-core').version, zod: installed('zod').version };
const banner = [
  `// Still browser control layer ${packageJson.version}. Generated by browser-control/build.mjs: do not edit this file,`,
  `// change browser-control/src and build again. It holds that source (Apache-2.0), puppeteer-core ${versions.puppeteer}`,
  `// (Apache-2.0) and zod ${versions.zod} (MIT). Notices: ${NOTICES}.`,
].join('\n');

// ---------------------------------------------------------------------------------------------------------- bundle
// Two parts of the dependencies that the layer cannot reach are left out, which takes almost half off what the service
// worker parses at every start. Each replacement first checks that the file still looks as expected, so an upgrade that
// moves things fails the build instead of quietly shipping something else.
const slim = {
  name: 'slim',
  setup(setup) {
    // WebDriver BiDi and chromium-bidi behind it: the layer always connects with protocol 'cdp' (checked below).
    setup.onLoad({ filter: /[\\/]puppeteer-core[\\/]lib[\\/]puppeteer[\\/]bidi[\\/]BrowserConnector\.js$/ }, async args => {
      const source = await readFile(args.path, 'utf8');
      if (!/export async function _connectToBiDiBrowser\(/.test(source)) throw new Error('puppeteer-core changed its BiDi connector: review the slim plugin in build.mjs.');
      return { loader: 'js', contents: "export async function _connectToBiDiBrowser() {\n  throw new Error('WebDriver BiDi is not part of this build: the layer connects with CDP.');\n}\n" };
    });
    // zod's error messages in some sixty languages: only English, its default, is ever used.
    setup.onLoad({ filter: /[\\/]zod[\\/]v4[\\/]locales[\\/]index\.js$/ }, async args => {
      const source = await readFile(args.path, 'utf8');
      if (!source.includes('export { default as en } from "./en.js";')) throw new Error('zod changed its locale index: review the slim plugin in build.mjs.');
      return { loader: 'js', contents: 'export { default as en } from "./en.js";\n' };
    });
  },
};
if (!/protocol: 'cdp'/.test(await readFile(join(here, 'src/host/puppeteer.ts'), 'utf8'))) {
  throw new Error('src/host/puppeteer.ts no longer connects with protocol \'cdp\': the BiDi code must then stay in the bundle.');
}

const result = await build({
  absWorkingDir: here,
  entryPoints: ['entry.ts'],
  outfile: 'layer.js',
  write: false,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  // The extension's minimum Chrome version (extension/manifest.json).
  target: ['chrome120'],
  minify: true,
  // Licence comments of the bundled code go to the notices file, not into the worker's script.
  legalComments: 'external',
  metafile: true,
  logLevel: 'warning',
  tsconfig: 'tsconfig.json',
  banner: { js: banner },
  // puppeteer-core's build for extensions and pages.
  conditions: ['browser', 'module', 'import', 'default'],
  mainFields: ['browser', 'module', 'main'],
  alias: {
    // connect() imports both for its `channel` option, which the layer never passes.
    '@puppeteer/browsers': resolve(here, 'src/host/puppeteer-browsers-stub.ts'),
    'node:path': resolve(here, 'stubs/node-path.ts'),
  },
  plugins: [slim],
});

const outputs = new Map(result.outputFiles.map(file => [file.path.slice(here.length + 1).split('\\').join('/'), file]));
const layerFile = outputs.get('layer.js');
if (!layerFile) throw new Error('esbuild wrote no layer.js.');
const layerText = layerFile.text.endsWith('\n') ? layerFile.text : `${layerFile.text}\n`;
const legal = outputs.get('layer.js.LEGAL.txt')?.text || '';

const meta = result.metafile.outputs['layer.js'];
if (!meta) throw new Error('esbuild reported no output for layer.js.');
if (meta.imports.length) throw new Error(`layer.js must import nothing, but imports ${meta.imports.map(entry => entry.path).join(', ')}.`);

// ---------------------------------------------------------------------------------------------- load and inspect it
// A service worker runs it with chrome.* present; here an empty object is enough, because nothing calls Chrome until
// a controller is created.
globalThis.chrome ??= {};
const moduleUrl = `data:text/javascript;base64,${Buffer.from(layerText).toString('base64')}`;
const { loadBrowserControl } = await import(moduleUrl);
if (typeof loadBrowserControl !== 'function') throw new Error('layer.js must export loadBrowserControl.');
const layer = await loadBrowserControl();
for (const name of ['createChromeController', 'TOOL_SPECS', 'argsJsonSchema', 'PROBE_SOURCE', 'ERROR_CODES', 'siteOf']) {
  if (!(name in layer)) throw new Error(`The layer does not export ${name}.`);
}
// The probe is a function turned into text and evaluated in the page, so it must stand alone: a helper the bundler
// put outside it would be undefined there.
new vm.Script(layer.PROBE_SOURCE, { filename: 'probe.js' });
const helper = layer.PROBE_SOURCE.match(/\b__(?:name|publicField|privateGet|privateSet|privateAdd|async|spreadValues|spreadProps|objRest|esm|esmMin|commonJS|toESM|export)\b/);
if (helper) throw new Error(`The probe refers to the bundler helper ${helper[0]}, which does not exist in a page.`);

// ------------------------------------------------------------------------------------------------------- catalogue
const readOnlyOf = spec => {
  if (typeof spec.readOnly !== 'function') return { readOnly: spec.readOnly };
  // `tabs` is read-only for some of its actions: say which, as data.
  const actions = layer.argsJsonSchema(spec)?.properties?.action?.enum || [];
  return { readOnly: false, readOnlyActions: actions.filter(action => spec.readOnly({ action })) };
};
const tools = layer.TOOL_SPECS.filter(spec => spec.available).map(spec => {
  const schema = structuredClone(layer.argsJsonSchema(spec));
  delete schema.$schema;
  return { name: spec.name, capability: spec.capability, ...readOnlyOf(spec), description: spec.description, schema };
});
const catalogueText = [
  '// The browser control layer\'s tool catalogue as data. Generated by browser-control/build.mjs from the layer\'s own',
  '// schemas: do not edit this file, change browser-control/src and build again. The assistant builds its browser tool',
  '// definitions from it (lib/ai/browser-tools.js) without loading the layer, which only the service worker does.',
  `export const LAYER_VERSION = ${JSON.stringify(packageJson.version)};`,
  `export const LAYER_ERROR_CODES = Object.freeze(${JSON.stringify([...layer.ERROR_CODES])});`,
  `export const LAYER_REFUSAL_NOTICE = ${JSON.stringify(layer.REFUSAL_NOTICE)};`,
  `export const LAYER_TOOLS = Object.freeze(${JSON.stringify(tools, null, 2)});`,
  '',
].join('\n');

// --------------------------------------------------------------------------------------------------------- notices
const packagesInBundle = new Map();
for (const [input, info] of Object.entries(meta.inputs)) {
  if (!info.bytesInOutput) continue;
  const match = input.match(/(?:^|\/)node_modules\/((?:@[^/]+\/)?[^/]+)\//);
  if (match) packagesInBundle.set(match[1], (packagesInBundle.get(match[1]) || 0) + info.bytesInOutput);
}
const licenceFile = async name => {
  for (const candidate of ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'LICENCE']) {
    const file = join(here, 'node_modules', name, candidate);
    if (existsSync(file)) return (await readFile(file, 'utf8')).replace(/\r\n/g, '\n').trimEnd();
  }
  return '';
};
const apache = (await readFile(join(here, 'LICENSE'), 'utf8')).replace(/\r\n/g, '\n').trimEnd();
const sections = [
  'Notices for extension/lib/browser-control/layer.js',
  '',
  'That file is generated by browser-control/build.mjs. It contains the browser control layer of Still Agent',
  '(browser-control/src in this repository) and the npm packages listed below. Nothing in it was changed by hand.',
  '',
  '================================================================================',
  `Still Agent browser control layer ${packageJson.version}`,
  'Licensed under the Apache License, Version 2.0 (the full text is at the end of this file).',
  '',
  (await readFile(join(here, 'NOTICE'), 'utf8')).replace(/\r\n/g, '\n').trimEnd(),
];
const names = [...packagesInBundle.keys()].sort();
const packagePins = {};
for (const name of names) {
  const manifest = installed(name);
  packagePins[name] = manifest.version;
  const repository = typeof manifest.repository === 'string' ? manifest.repository : manifest.repository?.url || manifest.homepage || '';
  const text = await licenceFile(name);
  sections.push('', '================================================================================',
    `${name} ${manifest.version}`, `Licence: ${manifest.license || 'see the package'}${repository ? `\nSource: ${repository.replace(/^git\+/, '')}` : ''}`);
  // Apache-2.0 is printed once, at the end.
  if (text && !/Apache License\s+Version 2\.0/.test(text)) sections.push('', text);
  else if (!text && manifest.license !== 'Apache-2.0') throw new Error(`${name} ships no licence file: add its notice by hand.`);
}
if (legal.trim()) {
  sections.push('', '================================================================================',
    'Licence comments from the bundled files (code that puppeteer-core itself bundles is among them)', '', legal.replace(/\r\n/g, '\n').trimEnd());
}
sections.push('', '================================================================================', 'Apache License, Version 2.0', '', apache, '');
const noticesText = sections.join('\n');

// ------------------------------------------------------------------------------------------------------------ pins
const pin = (path, text) => ({ path, bytes: Buffer.byteLength(text), sha256: sha256(text) });
const pins = {
  about: 'Written by browser-control/build.mjs and read by scripts/check.mjs. Do not edit: run "npm run build" in browser-control.',
  sourceHash: await layerSourceHash(root),
  packages: packagePins,
  files: [{ ...pin(LAYER, layerText), license: NOTICES }, pin(CATALOGUE, catalogueText), pin(NOTICES, noticesText)],
};
const pinsText = `${JSON.stringify(pins, null, 2)}\n`;

// ----------------------------------------------------------------------------------------------------------- write
const targets = [[resolve(extension, LAYER), layerText], [resolve(extension, CATALOGUE), catalogueText], [resolve(extension, NOTICES), noticesText], [PINS, pinsText]];
if (check) {
  const stale = [];
  for (const [file, text] of targets) {
    const current = existsSync(file) ? await readFile(file, 'utf8') : null;
    if (current !== text) stale.push(file.slice(root.length + 1));
  }
  if (stale.length) {
    process.stderr.write(`These files differ from a fresh build:\n${stale.map(file => `  ${file}`).join('\n')}\nRun "npm run build" in browser-control and commit the result.\n`);
    process.exit(1);
  }
  process.stdout.write('The committed layer, catalogue, notices and pins match a fresh build.\n');
} else {
  for (const [file, text] of targets) {
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, text);
  }
  const kb = bytes => `${(bytes / 1024).toFixed(0)} KB`;
  process.stdout.write(`${LAYER}: ${kb(Buffer.byteLength(layerText))}, ${tools.length} tools\n`);
  for (const [name, bytes] of [...packagesInBundle].sort((a, b) => b[1] - a[1])) process.stdout.write(`  ${kb(bytes).padStart(8)}  ${name}\n`);
  process.stdout.write(`source hash ${pins.sourceHash.slice(0, 16)}…\n`);
}
